#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	num;
	long	n;

	n = nb;
	if (n < 0)
	{
		write (1, "-", 1);
		n = -n;
	}
	if (n >= 10)
	{
		ft_putnbr(n / 10);
	}
	num = (n % 10) + '0';
	write (1, &num, 1);
}
